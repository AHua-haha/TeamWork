import {relative,sep,posix,basename} from 'node:path';
import type {ContextIndexSnapshot,ProjectContextNode} from '../../workspace/data/context-index.js';

export const dependencyRefreshMessageThreshold=64;
export interface FileDesignContext {
  snapshot:ContextIndexSnapshot;
  workingDesigns:readonly string[];
  readme(projectPath:string):Promise<string|undefined>;
}
export type FileDesignContextSource=(refresh:boolean)=>Promise<FileDesignContext>;
export const workingDesign=(path:string,working:readonly string[])=>working.some(root=>root==='.'||path===root||path.startsWith(root+'/'));

const contextOwners=new WeakMap<ContextIndexSnapshot,Map<string,string>>();

/** Ownership comes from the nearest explicit design binding, including RSI document locations. */
export function fileDesignOwner(root:string,path:string,context:FileDesignContext):string|undefined{
  const local=relative(root,path).split(sep).join('/');
  if(local==='..'||local.startsWith('../')||local.startsWith('/'))return;
  const snapshot=context.snapshot;
  if(local.startsWith('.rsi/')){
    if(!local.startsWith(snapshot.contextRoot+'/'))return;
    let directory=posix.dirname(local);
    let bindings=contextOwners.get(snapshot);
    if(!bindings){bindings=new Map(Object.values(snapshot.designSystems).map(system=>[system.contextDirectory,system.projectPath]));contextOwners.set(snapshot,bindings);}
    while(directory!=='.'){const owner=bindings.get(directory);if(owner!==undefined)return owner;directory=posix.dirname(directory);}
    return;
  }
  let node=local||'.';
  while(true){if(snapshot.designSystems[node])return node;if(node==='.')return;node=posix.dirname(node);}
}

/** Full design hierarchy with structural parents, optional summaries, and working markers only. */
function designTree(context:FileDesignContext):string{
  const snapshot=context.snapshot;
  type Branch={node:ProjectContextNode;children:Branch[]};
  const select=(node:ProjectContextNode):Branch|undefined=>{
    const children=(node.children??[]).flatMap(child=>{const branch=select(child);return branch?[branch]:[];});
    return node.designSystemPath!==undefined||children.length?{node,children}:undefined;
  };
  const root=select(snapshot.tree);if(!root)return 'Project';
  const label=(node:ProjectContextNode)=>{
    const system=node.designSystemPath===undefined?undefined:snapshot.designSystems[node.designSystemPath];
    const summary=system?.metadata.summary?.replace(/\s+/g,' ').trim();
    return `${node.projectPath==='.'?'Project':basename(node.projectPath)+(node.kind==='directory'?'/':'')}${system&&workingDesign(system.projectPath,context.workingDesigns)?' [working]':''}${summary?' — '+summary:''}`;
  };
  const lines=[label(root.node)];
  const visit=(branch:Branch,prefix:string)=>branch.children.forEach((child,i)=>{const last=i===branch.children.length-1;lines.push(prefix+(last?'└── ':'├── ')+label(child.node));visit(child,prefix+(last?'    ':'│   '));});
  visit(root,'');return lines.join('\n');
}
export async function replacementContext(context:FileDesignContext,dependencies:readonly string[]):Promise<string>{
  const sections=['<system_instruction>','This message is automatically generated by the system to provide useful context. It is not a user request.','## Design tree',designTree(context),'## Usage README context'];
  for(const path of dependencies){
    if(workingDesign(path,context.workingDesigns))continue;
    const system=context.snapshot.designSystems[path];
    const readme=system?await context.readme(path):undefined;
    sections.push(`### ${path}`,readme??'No README available.');
  }
  if(!dependencies.some(path=>!workingDesign(path,context.workingDesigns)))sections.push('No dependencies discovered.');
  sections.push('</system_instruction>');return sections.join('\n\n');
}
