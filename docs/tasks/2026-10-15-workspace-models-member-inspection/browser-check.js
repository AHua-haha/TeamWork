async page => {
  const assert = (ok, message) => {if (!ok) throw new Error(message);};
  const state = () => page.evaluate(() => window.__reviewState());
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Add workspace',exact:true}).click();
  let dialog=page.getByRole('dialog');
  assert(await dialog.getByRole('button',{name:'Create workspace',exact:true}).isDisabled(),'Creation requires models');
  await dialog.getByRole('textbox',{name:'Name',exact:true}).fill('Review project');
  await dialog.getByRole('textbox',{name:/^Folder/}).fill('/tmp/review-project');
  await dialog.getByLabel('Add workspace model').selectOption('["provider","model-a"]');
  await dialog.getByRole('button',{name:'Create workspace',exact:true}).click();
  await page.getByRole('button',{name:'Show design, team and files',exact:true}).click();
  await page.getByRole('button',{name:'Team',exact:true}).click();
  await page.getByRole('button',{name:'Inspect harness',exact:true}).click();
  await page.getByRole('heading',{name:'Project harness',exact:true}).waitFor();
  await page.getByText('prompts/member.md',{exact:true}).click();
  assert(await page.getByText('Maintain the current project design.',{exact:true}).isVisible(),'Accepted prompt visible');
  assert(await page.locator('.member-inspection input, .member-inspection select, .member-inspection textarea').count()===0,'No member mutation controls');
  await page.screenshot({path:'output/playwright/workspace-member-inspection-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Workspace models',exact:true}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByLabel('Add workspace model').selectOption('["provider","model-b"]');
  await dialog.getByRole('radio',{name:/model-b/}).check();
  await page.evaluate(() => window.__reviewConflict());
  await dialog.getByRole('button',{name:'Save workspace models',exact:true}).click();
  await dialog.getByRole('alert').waitFor();
  assert(await dialog.getByRole('radio',{name:/model-b/}).isChecked(),'Conflict retains draft and chosen default');
  await dialog.getByRole('button',{name:'Reload saved settings',exact:true}).click();
  await dialog.getByRole('radio',{name:/model-a/,checked:true}).waitFor();
  assert(await dialog.getByRole('radio',{name:/model-a/}).isChecked(),'Explicit reload restores saved choice');
  await dialog.getByLabel('Add workspace model').selectOption('["provider","model-b"]');
  await dialog.getByRole('radio',{name:/model-b/}).check();
  await dialog.getByText('Run options',{exact:true}).nth(1).click();
  await dialog.getByRole('spinbutton',{name:'Maximum output tokens',exact:true}).fill('500');
  await dialog.getByRole('button',{name:'Save workspace models',exact:true}).click();
  await dialog.waitFor({state:'detached'});
  assert((await state()).record.value.defaultModel.modelId==='model-b','Default persisted');
  assert((await state()).record.value.models[1].maxTokens===500,'Per-model options persisted');
  assert(await page.locator('.member-card .member-facts').first().getByText('model-a · provider',{exact:true}).isVisible(),'Existing lead selection unchanged');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Workspace models',exact:true}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByRole('radio',{name:/model-b/}).waitFor();
  await dialog.getByText('Run options',{exact:true}).nth(1).click();
  const bounds=await dialog.boundingBox();
  assert(bounds && bounds.x>=0 && bounds.x+bounds.width<=390,'Mobile dialog fits viewport');
  await page.screenshot({path:'output/playwright/workspace-models-mobile.png',fullPage:true});
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Add workspace',exact:true}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByRole('textbox',{name:'Name',exact:true}).fill('Review project');
  await dialog.getByRole('textbox',{name:/^Folder/}).fill('/tmp/review-project');
  await dialog.getByRole('radio',{name:'Use an existing folder',exact:true}).check();
  await dialog.getByLabel('Add workspace model').selectOption('["provider","model-b"]');
  await dialog.getByRole('button',{name:'Create workspace',exact:true}).click();
  await dialog.waitFor({state:'detached'});
  const result=await state(), creates=result.writes.filter(w=>w.path==='/workspaces');
  assert(creates.length===2 && creates[0].body.adopt===false && creates[1].body.adopt===true,'Create/adopt payloads correct');
  assert(creates[0].body.models.defaultModel.modelId==='model-a' && creates[1].body.models.defaultModel.modelId==='model-b','Creation includes selected default');
  assert(!result.writes.some(w=>w.path.includes('/team/members')),'No member HTTP mutations');
  assert(!result.unexpected.length,JSON.stringify(result.unexpected));
  assert(!result.errors.length,JSON.stringify(result.errors));
  console.log('PASS: desktop/mobile create/adopt, accepted read-only member inspection, workspace model save/options, conflict draft/reload, preserved lead selection; no unexpected API calls or page errors.');
}
