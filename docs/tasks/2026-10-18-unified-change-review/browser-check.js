async page => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const control = action => page.evaluate(async action => (await fetch('/workspaces/review-control', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action }) })).json(), action);
  await page.setViewportSize({ width: 1600, height: 1050 });
  await page.getByRole('button', { name: 'Show design, team and files', exact: true }).click();
  const panel = page.getByRole('complementary', { name: 'Design, team and files', exact: true });
  await panel.getByRole('button', { name: 'Team', exact: true }).click();
  await panel.getByRole('button', { name: 'Open Lead active details', exact: true }).waitFor();
  assert(await panel.getByRole('tab', { name: 'Configuration changes', exact: true }).count() === 0, 'Team has no configuration subpage');
  await panel.getByRole('button', { name: 'Changes', exact: true }).click();
  await panel.getByRole('button', { name: 'Expand panel', exact: true }).click();
  const review = panel.getByRole('region', { name: 'Design and member changes', exact: true });
  await review.getByRole('button', { name: 'Approve members', exact: true }).waitFor();
  const nav = review.getByRole('navigation', { name: 'Changed files', exact: true });
  await nav.getByRole('button').first().waitFor();
  assert(await nav.getByRole('button').count() === 3, 'Design and member files share one flat list');
  const memberFile = nav.getByRole('button').filter({ hasText: 'members/backend/member.json' });
  await memberFile.click();
  await review.getByLabel('Diff for .rsi/members/backend/member.json', { exact: true }).waitFor();
  await page.screenshot({ path: 'output/playwright/unified-changes-desktop.png', animations: 'disabled' });
  await review.getByRole('button', { name: 'Approve members', exact: true }).click();
  await review.getByText('Member changes approved. Activate them when ready.', { exact: true }).waitFor();
  await review.getByText('Member activation is blocked', { exact: true }).waitFor();
  await memberFile.waitFor({ state: 'hidden' });
  assert(await nav.getByRole('button').count() === 2, 'Member approval leaves design changes pending');
  assert(await review.getByRole('button', { name: 'Activate members', exact: true }).isDisabled(), 'Missing accepted design blocks activation');
  await control('stale-design');
  await review.getByRole('button', { name: 'Approve design', exact: true }).click();
  await review.getByRole('alert').waitFor();
  assert(await nav.getByRole('button').count() === 2, 'Stale approval leaves pending files');
  await nav.getByRole('button').filter({ hasText: 'backend/design.md' }).click();
  await review.getByText('Revised while review was open.', { exact: true }).waitFor();
  await review.getByRole('button', { name: 'Approve design', exact: true }).click();
  await review.getByText('Design approved.', { exact: true }).waitFor();
  await review.getByText('No pending design or member changes.', { exact: true }).waitFor();
  assert(await review.getByRole('button', { name: 'Activate members', exact: true }).isEnabled(), 'Design approval unblocks the approved member config');
  await control('pending-member');
  await review.getByRole('button', { name: 'Refresh', exact: true }).click();
  await nav.getByRole('button').filter({ hasText: 'members/backend/member.json' }).waitFor();
  await review.getByRole('button', { name: 'Activate members', exact: true }).click();
  await review.getByText('Approved members activated.', { exact: true }).waitFor();
  assert(await nav.getByRole('button').count() === 1, 'Activation leaves later pending member edits untouched');
  await panel.getByRole('button', { name: 'Team', exact: true }).click();
  await panel.getByRole('button', { name: 'Open Backend active details', exact: true }).waitFor();
  await panel.getByText('Implement the approved backend design', { exact: true }).first().waitFor();
  assert(!(await panel.innerText()).includes('Later pending responsibility'), 'Active member uses approved bytes');
  await panel.getByRole('button', { name: 'Changes', exact: true }).click();
  await review.getByRole('button', { name: 'Approve members', exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'output/playwright/unified-changes-mobile.png', animations: 'disabled' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No page overflow at narrow width');
  await page.setViewportSize({ width: 1600, height: 1050 });
  await page.reload();
  await page.getByRole('button', { name: 'Show design, team and files', exact: true }).click();
  await panel.getByRole('button', { name: 'Changes', exact: true }).click();
  await nav.getByRole('button').filter({ hasText: 'members/backend/member.json' }).waitFor();
  assert(errors.length === 0, errors.join('\n'));
  return { result: 'pass', checks: 'new tab, old subpage removed, flat diff, separate approval, stale refusal, design-dependent activation, pending preservation, active team, mobile and reload' };
}
