async page => {
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const assert=(ok,message)=>{if(!ok)throw new Error(message);};
  const control=input=>page.evaluate(async input=>{const response=await fetch('/workspaces/test-control',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(input)});return response.json();},input);
  const a=page.locator('[data-entry-id="entry-a"]'), b=page.locator('[data-entry-id="entry-b"]');
  await page.setViewportSize({width:1440,height:980});
  await page.goto('http://127.0.0.1:4274/?workspace=stream-review');
  await a.getByRole('button',{name:'Lead: Show working history',exact:true}).waitFor();
  let state=await control({});assert(state.agents.a.follows>0&&state.agents.b.follows>0,'Both folded active runs are subscribed');
  const initialFollows=state.agents.a.follows;
  await control({action:'text',id:'a',text:'Let me check the model.'});
  await a.locator('.group-work .work-text').getByText('Let me check the model.',{exact:true}).waitFor({state:'attached'});
  assert(await a.locator('.group-final').count()===0,'Working prose must never appear in response area');
  assert(await a.locator('.group-work').isHidden(),'Folded work still receives streamed content');
  await a.getByRole('button',{name:'Lead: Show working history',exact:true}).click();
  await a.getByText('Let me check the model.',{exact:true}).waitFor();
  await control({action:'text',id:'a',text:'Let me check the model. Reading the configuration.'});
  await a.locator('.group-work').getByText('Let me check the model. Reading the configuration.',{exact:true}).waitFor();
  assert(await a.locator('.group-final').count()===0,'Working text updates only inside Work');
  await control({action:'text',id:'a',kind:'response',text:''});
  await a.locator('.group-final').waitFor({state:'attached'});
  assert(await a.locator('.group-work .work-line-label').filter({hasText:'final_response'}).count()===0,'Response action is routed outside even before its first text token');
  await control({action:'text',id:'a',kind:'response',text:'First streamed words'});
  await a.getByLabel('Live response',{exact:true}).getByText('First streamed words',{exact:true}).waitFor();
  await control({action:'text',id:'a',kind:'response',text:'First streamed words, now extended.'});
  await a.getByText('First streamed words, now extended.',{exact:true}).waitFor();
  assert(await a.locator('.group-work').getByText('First streamed words, now extended.',{exact:true}).count()===0,'Final-response stream never appears in Work');
  await a.getByText('Read src/workspace.ts',{exact:true}).waitFor();
  const style=await a.locator('.group-work').evaluate(el=>{const s=getComputedStyle(el);return {background:s.backgroundColor,border:s.borderLeftWidth,padding:s.padding};});
  assert(style.background==='rgba(0, 0, 0, 0)'&&style.border==='0px'&&style.padding==='0px','Work is unboxed, transparent and compact');
  const row=await a.locator('.work-tool summary').first().boundingBox();assert(row.height<=30,'Compact tool row');
  await a.locator('.work-tool summary').first().click();
  assert(await a.locator('pre[aria-label="Result"]').first().isVisible(),'Tool result opens');
  await page.screenshot({path:'output/playwright/streaming-work-desktop.png',fullPage:true,animations:'disabled'});
  await page.getByRole('button',{name:'Collapse sidebar',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert(!overflow,'No mobile page overflow');
  await page.screenshot({path:'output/playwright/streaming-work-mobile.png',fullPage:true,animations:'disabled'});
  await a.getByRole('button',{name:'Lead: Hide working history',exact:true}).click();
  state=await control({});assert(state.agents.a.follows===initialFollows,'Fold toggle retains active stream');
  await control({action:'text',id:'b',kind:'response',text:'Writer streams independently.'});
  await b.getByText('Writer streams independently.',{exact:true}).waitFor();
  await control({action:'disconnect',id:'a'});
  await page.waitForFunction(async initial => {const res=await fetch('/workspaces/test-control',{method:'POST',body:'{}'});return (await res.json()).agents.a.follows>initial;}, initialFollows);
  await a.getByText('First streamed words, now extended.',{exact:true}).waitFor();
  state=await control({});assert(state.agents.a.follows>initialFollows,'Active output reconnects');
  await control({action:'commit',id:'b'});
  await control({action:'publish',id:'b'});
  await b.locator('.group-run-info[data-status="completed"]').waitFor();
  await b.getByRole('button',{name:'Writer: Show working history',exact:true}).click();
  assert(await b.locator('.group-work').count()===0,'Empty work renders no area or placeholder');
  assert(!(await b.innerText()).includes('No intermediate'),'No empty-history sentence');
  assert(await b.getByText('Writer streams independently.',{exact:true}).count()===1,'Accepted final displayed once');
  await page.setViewportSize({width:1440,height:980});
  const long=Array.from({length:80},(_,i)=>`Paragraph ${i+1}: streaming keeps a readable report.`).join('\n\n');
  await page.locator('.group-viewport').evaluate(el=>{el.scrollTop=el.scrollHeight;el.dispatchEvent(new Event('scroll'));});
  await control({action:'text',id:'a',kind:'response',text:long});
  await page.waitForFunction(()=>{const el=document.querySelector('.group-viewport');return el.scrollHeight-el.scrollTop-el.clientHeight<4;});
  await page.locator('.group-viewport').evaluate(el=>{el.scrollTop=0;el.dispatchEvent(new Event('scroll'));});
  await control({action:'text',id:'a',kind:'response',text:long+'\n\nAnother streamed paragraph.'});
  await a.getByText('Another streamed paragraph.',{exact:true}).waitFor();
  assert(await page.locator('.group-viewport').evaluate(el=>el.scrollTop)<2,'Streaming preserves user scroll-up position');
  await control({action:'commit',id:'a'});
  await a.getByText('Another streamed paragraph.',{exact:true}).waitFor();
  await control({action:'publish',id:'a'});
  await a.locator('.group-run-info[data-status="completed"]').waitFor();
  assert(await a.locator('[data-preview]').count()===0,'Published response replaces preview');
  assert(await a.getByText('Another streamed paragraph.',{exact:true}).count()===1,'Final retained once');
  assert(JSON.stringify(await page.locator('.group-member').evaluateAll(els=>els.map(el=>el.dataset.entryId)))==='["entry-a","entry-b"]','Reverse completion preserves reservation order');
  assert(!errors.length,JSON.stringify(errors));
  console.log('PASS: working output stays inside Work, explicit response output stays outside, folded live streaming, parallel runs, expand/collapse retention, compact transparent work, empty final-only work, private reconnect, final replacement, reservation order, mobile layout and pinned/user-scrolled behavior.');
}
