async page => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const control = input => page.evaluate(async input => { const response = await fetch('/workspaces/test-control', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(input) }); return response.json(); }, input);
  await page.setViewportSize({ width: 1440, height: 980 });
  const response = page.locator('[data-entry-id="entry-a"]');
  await response.getByRole('button', { name: 'Lead: Hide working history', exact: true }).waitFor();
  await control({ action: 'text', id: 'a', tools: ['one', 'timeout', 'two'].map((name, index) => ({ id: `fetch-${index}`, name: 'web_fetch', arguments: { url: `https://example.com/${name}` } })) });
  await control({ action: 'commit', id: 'a' });
  const group = response.locator('.work-tool-set');
  await group.locator(':scope > summary').getByText('1 failed', { exact: true }).waitFor();
  await group.locator(':scope > summary').click();
  assert(await group.locator('.work-tool.failed').count() === 1, 'One failed call, not a failed group');
  await page.mouse.move(100, 30);
  const rows = group.locator('.work-tool > summary');
  const colors = await rows.evaluateAll(elements => elements.map(element => getComputedStyle(element).color));
  const groupColor = await group.locator(':scope > summary').evaluate(element => getComputedStyle(element).color);
  assert(colors.length === 3 && colors[0] === colors[2], 'Successful siblings have the same neutral color');
  assert(colors[1] === 'rgb(161, 78, 64)' && colors[0] !== colors[1], 'Only the failed row is red');
  assert(groupColor === colors[0], 'Aggregate summary stays neutral');
  await rows.nth(1).hover();
  assert(await rows.nth(1).evaluate(element => getComputedStyle(element).color) === colors[1], 'Failure indication survives hover');
  await rows.nth(1).click();
  await group.getByText('Web request timed out. error_code: web_timeout; retryable: true', { exact: true }).waitFor();
  assert(await group.locator('.work-tool.failed pre').last().evaluate(element => getComputedStyle(element).color) === colors[0], 'Error detail does not tint its whole group');
  await page.mouse.move(100, 30);
  await page.screenshot({ path: 'output/playwright/recoverable-tool-errors-desktop.png', animations: 'disabled' });
  await control({ action: 'text', id: 'a', text: 'One source timed out; using the other two sources.' });
  await response.getByText('One source timed out; using the other two sources.', { exact: true }).waitFor();
  await control({ action: 'commit', id: 'a' }); await control({ action: 'publish', id: 'a' });
  await response.getByText('Completed', { exact: true }).waitFor();
  await response.getByRole('button', { name: 'Lead: Show working history', exact: true }).click();
  assert(await response.locator('.group-final').getByText('One source timed out; using the other two sources.', { exact: true }).count() === 1, 'A recovered run has one accepted final');
  await page.reload();
  await response.getByText('Completed', { exact: true }).waitFor();
  await response.getByRole('button', { name: 'Lead: Show working history', exact: true }).click();
  await group.locator(':scope > summary').click();
  assert(await group.locator('.work-tool.failed').count() === 1, 'Reload preserves per-call failure state');
  await page.setViewportSize({ width: 390, height: 844 });
  const sidebar = page.getByRole('button', { name: 'Collapse sidebar', exact: true });
  if (await sidebar.isVisible()) await sidebar.click();
  await page.screenshot({ path: 'output/playwright/recoverable-tool-errors-mobile.png', animations: 'disabled' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No narrow page overflow');
  assert(errors.length === 0, errors.join('\n'));
  return { result: 'pass', colors, groupColor, checks: 'individual failure color, neutral siblings/group/details, hover, disclosures, continued output, final, reload, narrow layout' };
}
