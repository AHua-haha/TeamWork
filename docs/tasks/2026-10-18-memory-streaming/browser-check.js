async page => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const errors = [], streams = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (/\/agents\/[^/]+\/follow\?/.test(response.url())) void response.text().then(text => streams.push(text)).catch(() => {}); });
  const advance = () => page.evaluate(() => fetch('/workspaces/fixture-advance', { method: 'POST' }).then(r => r.json()));
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.getByRole('textbox', { name: 'Message the team', exact: true }).fill('Check the streaming contract.');
  await page.getByRole('button', { name: 'Send ↗', exact: true }).click();
  await page.waitForFunction(() => [...document.querySelectorAll('.work-text')].some(node => node.textContent.includes('checking')));
  assert(await page.locator('.group-final').count() === 0, 'unaccepted streaming text stays in working area');
  await page.getByText('I am checking the design and its implementation contract.', { exact: true }).waitFor();
  await page.screenshot({ path: 'output/playwright/memory-stream-live.png' });
  await page.reload();
  await page.getByRole('textbox', { name: 'Message the team', exact: true }).waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('.group-run-pill')].some(node => node.textContent.includes('Working')));
  await advance();
  await page.getByText('Streaming completes correctly.', { exact: true }).waitFor();
  assert(await page.locator('.group-final').count() === 0, 'new message resumes streaming after the lost earlier start');
  await advance();
  await page.locator('.group-final').getByText('Streaming completes correctly.', { exact: true }).waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('.group-run-pill')].some(node => node.textContent.includes('Completed')));
  assert(await page.locator('.group-work:visible').count() === 0, 'accepted final folds working area');
  await page.getByRole('button', { name: 'Lead: Show working history', exact: true }).click();
  await page.getByText('I am checking the design and its implementation contract.', { exact: true }).waitFor();
  assert(await page.getByText('Streaming completes correctly.', { exact: true }).count() === 1, 'no final duplication in expanded work');
  assert(!(await page.locator('body').innerText()).includes('Hidden fixture reasoning'), 'thinking hidden');
  assert(await page.locator('.work-tool').count() === 1, 'tool call displayed');
  await page.screenshot({ path: 'output/playwright/memory-stream-completed.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'output/playwright/memory-stream-mobile.png' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no narrow viewport overflow');
  await page.reload();
  await page.locator('.group-final').getByText('Streaming completes correctly.', { exact: true }).waitFor();
  assert(errors.length === 0, errors.join('\n'));
  assert(streams.length > 0, 'execution stream captured');
  assert(streams.every(text => !text.includes('"partial":')), 'no cumulative partial on wire');
  assert(streams.some(text => text.includes('"version":2') && text.includes('"type":"text_delta"')), 'compact v2 progress delivered');
  return { result: 'pass', checks: 'incremental working text, evicted-start reload, SQL recovery and next message start, tool display, hidden thinking, final folding/deduplication, desktop/mobile and durable reload', streamBytes: streams.map(text => text.length) };
}
