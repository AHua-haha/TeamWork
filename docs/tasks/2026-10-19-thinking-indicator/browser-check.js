async page => {
  await page.goto('http://127.0.0.1:5284/?workspace=thinking-review');
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const control = action => page.evaluate(async action => {
    const response = await fetch('/workspaces/test-control', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(typeof action === 'string' ? { action } : action) });
    if (!response.ok) throw new Error('Fixture control failed'); return response.json();
  }, action);
  const article = page.locator('[data-entry-id="thinking-entry"]');
  const row = article.getByRole('status', { name: 'Lead is thinking', exact: true });
  const absent = () => row.waitFor({ state: 'hidden' });
  const privateContentAbsent = async () => assert(!(await page.locator('body').textContent()).includes('PRIVATE_REASONING_NEVER_RENDER'), 'Thinking content must never enter the DOM');
  await page.setViewportSize({ width: 1440, height: 980 });
  await article.getByRole('button', { name: 'Lead: Hide working history', exact: true }).waitFor();
  assert(await row.count() === 0, 'No indicator before thinking events');
  await control('thinking'); await row.waitFor(); await privateContentAbsent();
  const style = await row.evaluate(el => ({ height: el.getBoundingClientRect().height, color: getComputedStyle(el).color,
    animated: [...el.querySelectorAll('i')].every(dot => getComputedStyle(dot).animationName === 'work-thinking-pulse'), dots: el.querySelectorAll('i').length }));
  assert(style.height <= 30 && style.dots === 3 && style.animated, 'Compact animated thinking row');
  await page.screenshot({ path: 'output/playwright/thinking-indicator-desktop.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert(await row.locator('i').evaluateAll(dots => dots.every(dot => getComputedStyle(dot).animationName === 'none')), 'Reduced motion stops animation');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await article.getByRole('button', { name: 'Lead: Hide working history', exact: true }).click(); await absent();
  await control('thinking'); await absent();
  await article.getByRole('button', { name: 'Lead: Show working history', exact: true }).click(); await row.waitFor();
  await control('thinking-end'); await absent();
  await control('thinking'); await row.waitFor();
  await control({ action: 'text', text: 'Checking the implementation.' }); await absent();
  await article.getByText('Checking the implementation.', { exact: true }).waitFor();
  await control('thinking'); await row.waitFor(); await control('tool'); await absent();
  await article.locator('.work-tool-set > summary').waitFor();
  await control('thinking'); await row.waitFor(); await control('commit'); await absent();
  await page.reload(); await article.locator('.work-tool-set > summary').waitFor();
  assert(await row.count() === 0, 'Completed thinking blocks do not restore a historical status'); await privateContentAbsent();
  await control('thinking'); await row.waitFor(); await control('gap'); await absent();
  await control('thinking'); await row.waitFor(); await control('disconnect'); await absent();
  await control('resume'); await control('thinking'); await row.waitFor(); await privateContentAbsent();
  await page.setViewportSize({ width: 390, height: 844 });
  const collapseSidebar = page.getByRole('button', { name: 'Collapse sidebar', exact: true });
  if (await collapseSidebar.isVisible()) await collapseSidebar.click();
  await page.waitForFunction(() => { const panel = document.querySelector('.context-panel'); return !panel || panel.getBoundingClientRect().right <= 0; });
  await row.scrollIntoViewIfNeeded();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No narrow-screen page overflow');
  const bounds = await row.boundingBox(); assert(bounds && bounds.width > 0 && bounds.x >= 0 && bounds.x + bounds.width <= 391, 'Thinking row stays in narrow reading column');
  await page.screenshot({ path: 'output/playwright/thinking-indicator-mobile.png' });
  await control({ action: 'text', text: 'Implementation verified.' }); await absent();
  await control('publish');
  await article.locator('.group-final').getByText('Implementation verified.', { exact: true }).waitFor();
  await article.getByRole('button', { name: 'Lead: Show working history', exact: true }).waitFor();
  await article.getByRole('button', { name: 'Lead: Show working history', exact: true }).click();
  assert(await row.count() === 0, 'Final acceptance leaves no historical thinking indicator');
  await privateContentAbsent();
  await page.reload(); await article.locator('.group-final').waitFor();
  assert(await row.count() === 0, 'Reloaded final has no thinking indicator');
  assert(errors.length === 0, 'No browser exceptions: ' + errors.join(', '));
  return { result: 'pass', animated: true, reducedMotion: true, privacy: true, transitions: 'thinking/end/text/tool/completed/gap/disconnect/reconnect/final/reload', desktopAndMobile: true };
}
