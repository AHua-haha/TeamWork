import assert from 'node:assert/strict';
import { harnessPrompt } from '../../../backend/dist/src/harness-prompts.js';
import { implementationContextPath } from '../../../backend/dist/src/workspace-layout.js';
process.chdir('/tmp');
assert.match(harnessPrompt('design-template',{project:'Packaged project'}), /# Packaged project/);
assert.match(harnessPrompt('implementation-context-template',{design:'user/design.json'}), /### Usage examples/);
assert.match(harnessPrompt('implementation-context',{design:'user/example.json',context:'.rsi/context/agent/example.json.md'}), /user\/example.json/);
assert.equal(implementationContextPath('user/Example.json'),'agent/example.json.md');
assert.throws(()=>harnessPrompt('implementation-context'), /Missing harness prompt value/);
console.log('Packaged rules, templates, value rendering and context mapping load independently of cwd.');
