async page => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 980 });
  const reset = page.getByRole('button', { name: 'Reset group chat and member context', exact: true });
  await page.getByText('Old completed response', { exact: true }).waitFor();
  assert(await page.getByRole('alert').count() === 0, 'Initial stored history has no errors');
  await reset.click();
  const dialog = page.getByRole('dialog', { name: 'Reset chat and member context?' });
  await dialog.waitFor();
  assert((await dialog.innerText()).includes('member settings and harness history will be kept'), 'Confirmation names preserved data');
  await page.screenshot({ path: 'output/playwright/chat-reset-confirm-desktop.png', animations: 'disabled' });
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert(await page.getByText('Old completed response', { exact: true }).count() === 1, 'Cancel leaves chat intact');
  const second = await page.context().newPage();
  await second.goto(page.url());
  await second.getByText('Old completed response', { exact: true }).waitFor();
  await page.evaluate(() => fetch('/workspaces/test-control', { method: 'POST', body: JSON.stringify({ action: 'fail-next' }) }));
  await reset.click(); await dialog.getByRole('button', { name: 'Reset chat', exact: true }).click();
  await dialog.getByRole('alert').getByText('Wait for team finalization before resetting', { exact: true }).waitFor();
  assert(await page.getByText('Old completed response', { exact: true }).count() === 1, 'Backend refusal preserves history');
  await dialog.getByRole('button', { name: 'Reset chat', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('heading', { name: 'Work with your team' }).waitFor();
  await second.getByRole('heading', { name: 'Work with your team' }).waitFor();
  assert(await page.locator('.group-timeline article').count() === 0, 'Reset removes old message views');
  const input = page.getByRole('textbox', { name: 'Message the team' });
  await input.fill('Fresh test message'); await page.getByRole('button', { name: 'Send ↗', exact: true }).click();
  await page.locator('.group-timeline').getByText('Fresh test message', { exact: true }).waitFor();
  await second.locator('.group-timeline').getByText('Fresh test message', { exact: true }).waitFor();
  await second.reload(); await second.locator('.group-timeline').getByText('Fresh test message', { exact: true }).waitFor();
  assert(await second.getByText('Old completed response', { exact: true }).count() === 0, 'Reload cannot restore old history');
  await second.close();
  await page.setViewportSize({ width: 390, height: 844 });
  const closeSidebar = page.getByRole('button', { name: 'Close sidebar', exact: true });
  if (await closeSidebar.isVisible()) await closeSidebar.click();
  await reset.click(); await dialog.waitFor();
  await page.screenshot({ path: 'output/playwright/chat-reset-confirm-mobile.png', animations: 'disabled' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Narrow view has no page overflow');
  await dialog.getByRole('button', { name: 'Reset chat', exact: true }).click();
  await page.getByRole('heading', { name: 'Work with your team' }).waitFor();
  await page.reload(); await page.getByRole('heading', { name: 'Work with your team' }).waitFor();
  assert(await page.locator('.group-timeline article').count() === 0, 'Reload after a second reset remains empty');
  assert(errors.length === 0, errors.join('\n'));
  return { result: 'pass', checks: 'confirm, cancel, refusal, empty state, two clients, fresh input, reload, repeated reset, narrow layout', errors };
}
